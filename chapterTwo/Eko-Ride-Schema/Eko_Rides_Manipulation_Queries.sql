SELECT R.DRIVERID, D.NAME, SUM(R.FARE) AS TOTAL_REVENUE
FROM RIDES AS R
JOIN RIDERS AS RI
ON R.RIDERID = RI.RIDERID
JOIN DRIVERS AS D
ON D.DRIVERID = R.DRIVERID
GROUP BY D.DRIVERID, D.NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 1;

